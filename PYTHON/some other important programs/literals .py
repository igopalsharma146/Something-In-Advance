#literals in python
# literals are the values that are assigned to variables. They can be of different types such as integer, float, string, boolean, etc.
# example of literals
x = 10 # integer literal
y = 3.14 # float literal
z = "Hello, World!" # string literal
w = True # boolean literal
print(x) # output: 10
print(y) # output: 3.14
print(z) # output: Hello, World!
print(w) # output: True