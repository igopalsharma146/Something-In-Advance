# Floor= largest number in an array <= target
# CEIL= smallest number in an array >= target
print("\nfloor and ceil in int :")
import math
n = 45.99
print("N =",n)
print("Floor:", math.floor(n))
print("Ceil :", math.ceil(n))

n = 45.01
print("N =",n)
print("Floor:", math.floor(n))
print("Ceil :", math.ceil(n))

n = 45.00000001
print("N =",n)
print("Floor:", math.floor(n))
print("Ceil :", math.ceil(n))